# Manifest: write (deterministic Lua 5.1) and read back (for --only)
# ---------------------------------------------------------------------------
LUA_KEYWORDS = set("and break do else elseif end false for function if in local nil not or repeat return "
                   "then true until while".split())
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r") + '"'


def lua_key(k):
    if isinstance(k, str) and IDENT.match(k) and k not in LUA_KEYWORDS:
        return k
    return "[%s]" % lua_val(k)


def _ordered(d):
    return [k for k in INLINE_ORDER if k in d] + sorted((k for k in d if k not in INLINE_ORDER), key=str)


def lua_val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v.is_integer():
            return str(int(v))
        return ("%.4f" % v).rstrip("0").rstrip(".")
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, (list, tuple)):
        return "{ " + ", ".join(lua_val(x) for x in v) + " }" if v else "{}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        return "{ " + ", ".join("%s = %s" % (lua_key(k), lua_val(v[k])) for k in _ordered(v) if v[k] is not None) + " }"
    raise TypeError("cannot write %r to Lua" % (v,))


def _entry_lines(sec, key, e, title):
    cmt = (" -- " + title) if title else ""
    order = FIELD_ORDER[sec]
    fields = [f for f in order if e.get(f) is not None] + sorted((f for f in e if f not in order and e[f] is not None), key=str)
    nested = [f for f in fields if isinstance(e[f], dict)]
    flat = [f for f in fields if f not in nested]
    if not nested:
        return ["\t\t%s = { %s },%s" % (lua_key(key), ", ".join("%s = %s" % (lua_key(f), lua_val(e[f])) for f in flat), cmt)]
    lines = ["\t\t%s = {%s" % (lua_key(key), cmt)]
    if flat:
        lines.append("\t\t\t" + ", ".join("%s = %s" % (lua_key(f), lua_val(e[f])) for f in flat) + ",")
    for f in nested:
        v = e[f]
        if f == "anims":      # one animation per line keeps diffs readable
            lines.append("\t\t\t%s = {" % lua_key(f))
            for k in sorted(v, key=str):
                lines.append("\t\t\t\t%s = %s," % (lua_key(k), lua_val(v[k])))
            lines.append("\t\t\t},")
        else:
            lines.append("\t\t\t%s = %s," % (lua_key(f), lua_val(v)))
    lines.append("\t\t},")
    return lines


def render_manifest(header, man):
    t = titles()
    L = [header + "local _, ns = ...", "", "ns.ART = {"]
    for sec in SECTIONS:
        entries = man.get(sec) or {}
        if not entries:
            L.append("\t%s = {}," % sec)
            continue
        L.append("\t%s = {" % sec)
        for key in sorted(entries, key=str):
            L.extend(_entry_lines(sec, key, entries[key], t[sec].get(key)))
        L.append("\t},")
    L.append("}")
    return "\n".join(L) + "\n"


def manifest_header(text):
    if not text:
        return DEFAULT_HEADER
    hdr = []
    for ln in text.replace("\r\n", "\n").split("\n"):
        if ln.startswith("--"):
            hdr.append(ln)
        else:
            break
    return "\n".join(hdr) + "\n" if hdr else DEFAULT_HEADER


TOKEN = re.compile(r"""
    (?P<ws>\s+)
  | (?P<lcomment>--\[(?P<eq>=*)\[.*?\](?P=eq)\])
  | (?P<comment>--[^\n]*)
  | (?P<str>"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*')
  | (?P<num>0[xX][0-9a-fA-F]+|(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)
  | (?P<name>[A-Za-z_]\w*)
  | (?P<op>\.\.\.|[{}\[\]=,;.\-])
""", re.S | re.X)

_ESC = {"n": "\n", "t": "\t", "r": "\r", "a": "\a", "b": "\b", "f": "\f", "v": "\v", "\\": "\\", '"': '"', "'": "'", "\n": "\n"}


def _unescape(s):
    return re.sub(r"\\(\d{1,3}|.)", lambda m: chr(int(m.group(1))) if m.group(1).isdigit() else _ESC.get(m.group(1), m.group(1)),
                  s[1:-1], flags=re.S)


def _tokens(text):
    out, pos = [], 0
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m:
            raise ValueError("unexpected character %r at offset %d" % (text[pos], pos))
        pos = m.end()
        kind = m.lastgroup if m.lastgroup != "eq" else "lcomment"
        if kind in ("ws", "comment", "lcomment"):
            continue
        out.append((kind, m.group(kind)))
    out.append(("eof", ""))
    return out


def _parse_value(toks, i):
    kind, text = toks[i]
    if kind == "op" and text == "{":
        return _parse_table(toks, i)
    if kind == "str":
        return _unescape(text), i + 1
    if kind == "num":
        v = int(text, 16) if text.lower().startswith("0x") else (float(text) if re.search(r"[.eE]", text) else int(text))
        return v, i + 1
    if kind == "op" and text == "-":
        v, j = _parse_value(toks, i + 1)
        return -v, j
    if kind == "name" and text in ("true", "false", "nil"):
        return {"true": True, "false": False, "nil": None}[text], i + 1
    raise ValueError("unexpected %r" % text)


def _expect(toks, i, text):
    if toks[i][1] != text:
        raise ValueError("expected %r, found %r" % (text, toks[i][1]))
    return i + 1


def _parse_table(toks, i):
    i = _expect(toks, i, "{")
    d, arr = {}, []
    while toks[i][1] != "}":
        if toks[i][0] == "eof":
            raise ValueError("unterminated table")
        if toks[i][1] == "[":
            k, i = _parse_value(toks, i + 1)
            i = _expect(toks, i, "]")
            i = _expect(toks, i, "=")
            v, i = _parse_value(toks, i)
            d[k] = v
        elif toks[i][0] == "name" and toks[i + 1][1] == "=":
            v, j = _parse_value(toks, i + 2)
            d[toks[i][1]] = v
            i = j
        else:
            v, i = _parse_value(toks, i)
            arr.append(v)
        if toks[i][1] in (",", ";"):
            i += 1
    if arr and not d:
        return arr, i + 1
    for k, v in enumerate(arr, 1):
        d[k] = v
    return d, i + 1


def parse_manifest(text):
    toks = _tokens(text)
    for i in range(len(toks) - 4):
        if [t[1] for t in toks[i:i + 4]] == ["ns", ".", "ART", "="]:
            man, _ = _parse_table(toks, i + 4)
            if not isinstance(man, dict):
                raise ValueError("ns.ART is not a table")
            return {s: dict(man.get(s) or {}) for s in SECTIONS}
    raise ValueError("no 'ns.ART = { ... }' found")


def entry_files(sec, e):
    if sec == "bg":
        return [p["file"] for p in e.values() if isinstance(p, dict) and "file" in p]
    return [e["file"]] if isinstance(e, dict) and "file" in e else []


