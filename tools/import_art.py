def texture_names(a):
    k = a["kind"]
    if k == "sprite" or k == "ui":
        return [a["id"]]
    if k == "fx":
        return list(a["effects"])
    if k == "background":
        return [a["id"] + "_far", a["id"] + "_near"]
    if k == "icons":
        return list(a["icons"])
    return []


def manifest_keys(a):
    k = a["kind"]
    if k == "sprite":
        return [("sprites", a["id"])]
    if k == "fx":
        return [("fx", e) for e in a["effects"]]
    if k == "background":
        return [("bg", a["game"]["theme"])]
    if k == "ui":
        return [("ui", a["id"])]
    if k == "icons":
        return [("icons", i) for i in a["icons"]]
    return []


def check_spec():
    seen = {}
    for a in SPEC.ASSETS:
        for n in texture_names(a):
            if n.lower() in seen:
                raise SystemExit("spec error: texture name %s used by %s and %s" % (n, seen[n.lower()], a["id"]))
            seen[n.lower()] = a["id"]


def titles():
    t = {s: {} for s in SECTIONS}
    for a in SPEC.ASSETS:
        for sec, key in manifest_keys(a):
            t[sec][key] = a["title"]
    return t


