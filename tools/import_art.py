def pot(n):
    p = 1
    while p < n:
        p *= 2
    return p


def _window(c, axis, n, r):
    hi = [slice(None)] * c.ndim
    lo = [slice(None)] * c.ndim
    hi[axis] = slice(2 * r + 1, n + 2 * r + 1)
    lo[axis] = slice(0, n)
    return c[tuple(hi)] - c[tuple(lo)]


def box_sum(x, r):
    """Sum over a (2r+1) x (2r+1) window, zero outside the image (separable, via cumulative sums)."""
    x = np.asarray(x, dtype=np.float64)
    for axis in (0, 1):
        n = x.shape[axis]
        pad = [(0, 0)] * x.ndim
        pad[axis] = (r + 1, r)
        x = _window(np.cumsum(np.pad(x, pad), axis=axis), axis, n, r)
    return x


def dilate(mask, r):
    """Binary dilation with a (2r+1) square."""
    if r <= 0:
        return mask.copy()
    m = mask.astype(np.int32)
    for axis in (0, 1):
        n = m.shape[axis]
        pad = [(0, 0), (0, 0)]
        pad[axis] = (r + 1, r)
        m = (_window(np.cumsum(np.pad(m, pad), axis=axis), axis, n, r) > 0).astype(np.int32)
    return m.astype(bool)


def label(mask):
    """8-connected components of a boolean image -> (labels int32, count); 0 is background.

    Works on horizontal runs of set pixels: each run is joined (union-find) with the
    runs of the row above that touch it, so the cost follows the number of runs."""
    H, W = mask.shape
    lab = np.zeros((H, W), np.int32)
    if H == 0 or W == 0 or not mask.any():
        return lab, 0
    p = np.zeros((H, W + 2), np.int8)
    p[:, 1:-1] = mask
    d = np.diff(p, axis=1)
    sr, sc = np.nonzero(d == 1)
    _, ec = np.nonzero(d == -1)        # exclusive run ends, same order as the starts
    n = len(sr)
    stride = W + 1
    sr64 = sr.astype(np.int64)
    S = sr64 * stride + sc
    E = sr64 * stride + ec
    prev = (sr64 - 1) * stride
    lo = np.searchsorted(E, prev + sc, "left")          # first run above with end >= my start
    hi = np.searchsorted(S, prev + ec, "right") - 1     # last run above with start <= my end
    cnt = np.maximum(hi - lo + 1, 0)
    parent = list(range(n))
    total = int(cnt.sum())
    if total:
        b = np.repeat(np.arange(n), cnt)
        a = np.repeat(lo, cnt) + (np.arange(total) - np.repeat(np.cumsum(cnt) - cnt, cnt))
        for x, y in zip(a.tolist(), b.tolist()):
            rx = x
            while parent[rx] != rx:
                rx = parent[rx]
            ry = y
            while parent[ry] != ry:
                ry = parent[ry]
            root = rx if rx < ry else ry
            parent[rx] = parent[ry] = parent[x] = parent[y] = root
    par = np.array(parent, dtype=np.int64)
    while True:                          # pointer jumping to the roots
        nxt = par[par]
        if np.array_equal(nxt, par):
            break
        par = nxt
    _, inv = np.unique(par, return_inverse=True)
    run_label = inv.astype(np.int64) + 1
    marks = np.zeros(H * stride + 1, np.int64)
    marks[S] = run_label
    marks[E] = -run_label
    flat = np.cumsum(marks)[:H * stride].reshape(H, stride)[:, :W]
    return flat.astype(np.int32), int(run_label.max())


def resize_rgba(img, w, h):
    """Resize straight-alpha float RGBA with premultiplied filtering (no dark or coloured halos)."""
    w, h = max(1, int(w)), max(1, int(h))
    if img.shape[1] == w and img.shape[0] == h:
        return img.copy()
    flt = LANCZOS if (w < img.shape[1] or h < img.shape[0]) else BICUBIC
    a = img[..., 3]
    out = np.empty((h, w, 4), np.float32)
    for i, ch in enumerate((img[..., 0] * a, img[..., 1] * a, img[..., 2] * a, a)):
        out[..., i] = np.asarray(Image.fromarray(np.ascontiguousarray(ch, dtype=np.float32)).resize((w, h), flt))
    np.clip(out, 0.0, 1.0, out=out)
    a2 = out[..., 3]
    a2[a2 < 1.0 / 512] = 0.0
    nz = a2 > 0
    rgb = out[..., :3]
    rgb[nz] = np.minimum(rgb[nz] / a2[nz][:, None], 1.0)
    rgb[~nz] = 0.0
    return out


def trim(img, thr=0.004):
    m = img[..., 3] > thr
    if not m.any():
        return None
    ys = np.nonzero(m.any(axis=1))[0]
    xs = np.nonzero(m.any(axis=0))[0]
    return img[ys[0]:ys[-1] + 1, xs[0]:xs[-1] + 1]


def bleed(tex, r=2):
    """Give fully transparent pixels next to a drawing the drawing's colour, so the
    game's bilinear filtering does not pull dark edges in."""
    a = tex[..., 3]
    empty = a <= 0
    if not empty.any() or empty.all():
        return tex
    ws = box_sum(a, r)
    fill = empty & (ws > 1e-6)
    if fill.any():
        cs = box_sum(tex[..., :3] * a[..., None], r)
        tex[..., :3][fill] = (cs[fill] / ws[fill][:, None]).astype(np.float32)
    return tex


def to_u8(tex):
    return np.clip(np.rint(tex * 255.0), 0, 255).astype(np.uint8)


def paste(tex, img, x, y, box):
    """Copy img into tex at (x, y), clipped to box = (x0, y0, x1, y1).
    Returns the highest alpha that fell outside the box (0 when nothing visible was cut)."""
    h, w = img.shape[:2]
    X0, Y0 = max(x, box[0]), max(y, box[1])
    X1, Y1 = min(x + w, box[2]), min(y + h, box[3])
    if X1 <= X0 or Y1 <= Y0:
        return float(img[..., 3].max()) if img.size else 0.0
    tex[Y0:Y1, X0:X1] = img[Y0 - y:Y1 - y, X0 - x:X1 - x]
    a = img[..., 3].copy()
    a[Y0 - y:Y1 - y, X0 - x:X1 - x] = 0
    return float(a.max())


def load_image(path):
    with Image.open(path) as im:
        im.load()
        has_alpha = im.mode in ("RGBA", "LA", "PA", "RGBa", "La") or "transparency" in im.info
        arr = np.asarray(im.convert("RGBA"), dtype=np.float32) / 255.0
    return arr, has_alpha


def write_tga(path, arr):
    """32-bit uncompressed true-colour TGA, bottom-left origin (what WoW reads), then
    read it back with Pillow to make sure the file shows what we meant."""
    h, w = arr.shape[:2]
    header = struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, w, h, 32, 8)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        f.write(header)
        f.write(np.ascontiguousarray(arr[::-1, :, [2, 1, 0, 3]]).tobytes())
    os.replace(tmp, path)
    with Image.open(path) as im:
        back = np.asarray(im.convert("RGBA"))
    if back.shape != arr.shape or not np.array_equal(back, arr):
        raise RuntimeError("%s: the TGA read back differs from what was written" % path)


# ---------------------------------------------------------------------------
# Background removal
# ---------------------------------------------------------------------------
def _ring(H, W, bw):
    m = np.zeros((H, W), bool)
    m[:bw] = m[-bw:] = True
    m[:, :bw] = m[:, -bw:] = True
    return m


def _dominant(px):
    q = (px // 16).astype(np.int64)
    key = (q[:, 0] * 16 + q[:, 1]) * 16 + q[:, 2]
    k = np.bincount(key, minlength=4096).argmax()
    c = np.median(px[key == k], axis=0)
    near = np.linalg.norm(px - c, axis=1) < 48
    return np.median(px[near], axis=0)


def _is_magenta(c):
    return c[0] > 150 and c[2] > 150 and c[1] < 110 and min(c[0], c[2]) - c[1] > 90


def _fit_background(rgb, sel, H, W):
    """Smooth background model: a quadratic surface per channel fitted to the border."""
    ys, xs = np.nonzero(sel)
    if len(ys) > 40000:
        step = len(ys) // 40000 + 1
        ys, xs = ys[::step], xs[::step]

    def terms(x, y):
        return [np.ones_like(x), x, y, x * x, y * y, x * y]

    xn = xs / max(W - 1, 1) * 2.0 - 1.0
    yn = ys / max(H - 1, 1) * 2.0 - 1.0
    X = np.stack(terms(xn, yn), -1)
    Y = rgb[ys, xs].astype(np.float64)
    coef = np.linalg.lstsq(X, Y, rcond=None)[0]
    res = np.linalg.norm(X @ coef - Y, axis=1)
    keep = res <= max(3.0 * 1.4826 * np.median(res), 3.0)
    if keep.sum() > 12:
        coef = np.linalg.lstsq(X[keep], Y[keep], rcond=None)[0]
    gx = np.linspace(-1.0, 1.0, W)[None, :, None]
    gy = np.linspace(-1.0, 1.0, H)[:, None, None]
    model = sum(c[None, None, :] * t for c, t in zip(coef, terms(gx, gy)))
    return np.broadcast_to(model, (H, W, 3)).astype(np.float32)


def _clean_specks(a, H, W):
    m = a > 0.1
    lab, n = label(m)
    if n:
        area = np.bincount(lab.ravel(), minlength=n + 1)
        small = area < max(4, (H * W) // 200000)
        small[0] = False
        a[small[lab]] = 0.0
    return a


def _grow_background(bg, weak):
    """Extend the background through weak pixels (close to the background colour: noise,
    JPEG colour bleeding) that are not right next to a surely-foreground pixel. The
    thick dark outlines the style asks for stop the growth."""
    can = weak & ~dilate(~weak, 2)
    lab, n = label(bg | can)
    if not n:
        return bg
    keep = np.zeros(n + 1, bool)
    keep[np.unique(lab[bg])] = True
    keep[0] = False
    return keep[lab]


def _suppress_magenta(rgb, sel):
    """Pull pixels that lean towards magenta (R and B above G) back to neutral."""
    if not sel.any():
        return
    px = rgb[sel]
    s = np.clip(np.minimum(px[:, 0], px[:, 2]) - px[:, 1], 0, None)
    px[:, 0] -= s
    px[:, 2] -= s
    rgb[sel] = px


def remove_background(rgba, has_alpha, where, log, holes=True, need_bg=False):
    """Returns float RGBA (0..1) with the background made transparent, and the mode used.
    need_bg: no detectable background is an error (sheets of separate drawings)."""
    H, W = rgba.shape[:2]
    rgb = rgba[..., :3] * 255.0
    a = rgba[..., 3].copy()
    ring = _ring(H, W, max(2, int(round(min(H, W) * 0.006))))
    fr = max(2, int(round(min(H, W) / 400.0)))      # width of the soft edge zone

    if has_alpha and ((a[ring] < 0.5).mean() > 0.5 or (a < 0.5).mean() > 0.08):
        a[a < 0.04] = 0.0
        m = np.minimum(rgb[..., 0], rgb[..., 2]) - rgb[..., 1]
        # a magenta matte left behind by the model (cut out of a magenta fill, often a pixel
        # too loosely): peel nearly pure magenta edge pixels, ring by ring, each pixel once
        est = np.clip(1.0 - m / 255.0, 0, 1)
        opaque = max(1, int((a > 0).sum()))
        done = np.zeros((H, W), bool)
        edge = dilate(a <= 0, 2) & (a > 0)
        matte_mode = (edge & (m > 0.85 * 255)).sum() > 0.001 * opaque
        if matte_mode:
            a[est < 0.15] = 0.0      # also fills of narrow gaps the cut-out closed over
        for _ in range(4 if matte_mode else 0):
            edge = dilate(a <= 0, 2) & (a > 0) & ~done
            if not (edge & (m > 0.5 * 255)).any():
                break
            a[edge] *= np.clip((est[edge] - 0.15) / 0.75, 0, 1)
            a[a < 0.04] = 0.0
            done |= edge
        edge = (dilate(a <= 0, 2) & (a > 0)) | (done & (a > 0))
        _suppress_magenta(rgb, edge & (m > (0.2 if matte_mode else 0.35) * 255))
        a = _clean_specks(a, H, W)
        return np.dstack([rgb / 255.0, a]).astype(np.float32), "transparent"

    px = rgb[ring]
    c = _dominant(px)
    near_c = np.linalg.norm(px - c, axis=1) < 48
    if _is_magenta(c) and near_c.mean() > 0.25:
        m = np.minimum(rgb[..., 0], rgb[..., 2]) - rgb[..., 1]
        m_bg = float(np.median(m[ring][near_c]))
        m_bg = max(m_bg, 60.0)
        est = np.clip(1.0 - m / m_bg, 0, 1)          # foreground opacity, assuming non-magenta paint
        hard = _grow_background(est < 0.15, est < 0.4)
        zone = dilate(hard, fr) & ~hard
        a = np.ones((H, W), np.float32)
        a[hard] = 0.0
        a[zone] = np.clip((est[zone] - 0.15) / 0.75, 0, 1)
        z = zone & (a > 0.05)
        if z.any():
            az = a[z][:, None]
            rgb[z] = np.clip((rgb[z] - (1.0 - az) * c[None, :]) / az, 0, 255)
        _suppress_magenta(rgb, zone)
        a = _clean_specks(a, H, W)
        return np.dstack([rgb / 255.0, a]).astype(np.float32), "magenta"

    if near_c.mean() < 0.45:
        if need_bg:
            raise AssetError("%s: background not detected (no transparency and no uniform border colour); "
                             "use a transparent or flat magenta background" % where)
        log.warn(where, "background not detected (no transparency and no uniform border colour); kept opaque")
        return np.dstack([rgb / 255.0, np.ones((H, W), np.float32)]).astype(np.float32), "none"

    model = _fit_background(rgb, ring & (np.linalg.norm(rgb - c, axis=2) < 48), H, W)
    dist = np.linalg.norm(rgb - model, axis=2)
    tol = float(np.clip(np.percentile(dist[ring][near_c], 99) * 1.25 + 4.0, 10.0, 60.0))
    near = dist <= tol
    lab, n = label(near)
    edge_labels = np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))
    is_bg = np.zeros(n + 1, bool)
    is_bg[edge_labels] = True
    if holes and n:
        area = np.bincount(lab.ravel(), minlength=n + 1)
        mean_d = np.bincount(lab.ravel(), weights=dist.ravel(), minlength=n + 1) / np.maximum(area, 1)
        is_bg |= (area >= max(24, (H * W) // 40000)) & (mean_d <= 0.6 * tol)
    is_bg[0] = False
    bg = _grow_background(is_bg[lab], dist < 2.0 * tol)
    zone = dilate(bg, fr) & ~bg
    a = np.ones((H, W), np.float32)
    a[bg] = 0.0
    zy, zx = np.nonzero(zone)
    if len(zy):
        # the foreground colour of an edge pixel: the most background-unlike pixel nearby
        best_d = dist[zy, zx].copy()
        best_c = rgb[zy, zx].copy()
        for dy in range(-2, 3):
            for dx in range(-2, 3):
                yy = np.clip(zy + dy, 0, H - 1)
                xx = np.clip(zx + dx, 0, W - 1)
                dd = dist[yy, xx]
                better = dd > best_d
                best_d[better] = dd[better]
                best_c[better] = rgb[yy[better], xx[better]]
        B = model[zy, zx]
        P = rgb[zy, zx]
        FB = best_c - B
        den = (FB * FB).sum(1)
        alpha = np.clip(((P - B) * FB).sum(1) / np.maximum(den, 1e-6), 0, 1)
        weak = np.sqrt(den) < 1.5 * tol
        ramp = max(20.0, tol)
        alpha[weak] = np.clip((dist[zy, zx][weak] - tol) / ramp, 0, 1)
        ok = alpha > 0.05
        P[ok] = np.clip(B[ok] + (P[ok] - B[ok]) / alpha[ok][:, None], 0, 255)
        rgb[zy, zx] = P
        a[zy, zx] = np.where(alpha < 0.03, 0.0, alpha)
    a = _clean_specks(a, H, W)
    return np.dstack([rgb / 255.0, a]).astype(np.float32), "colour"


def prepare(path, where, log, holes=True, need_bg=True):
    arr, has_alpha = load_image(path)
    return remove_background(arr, has_alpha, where, log, holes, need_bg)


