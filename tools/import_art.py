def _font():
    try:
        return ImageFont.load_default()
    except Exception:  # pragma: no cover
        return None


def _on_checker(rgba_u8, sq=8):
    h, w = rgba_u8.shape[:2]
    yy, xx = np.mgrid[0:h, 0:w]
    v = np.where(((yy // sq + xx // sq) % 2) == 0, 0.93, 0.78).astype(np.float32)
    a = rgba_u8[..., 3:4].astype(np.float32) / 255.0
    rgb = rgba_u8[..., :3].astype(np.float32) / 255.0 * a + v[..., None] * (1 - a)
    return Image.fromarray(to_u8(rgb), "RGB")


def preview_sprite(tex, cw, ch, cols, n, foot_px, anims):
    rows = int(math.ceil(n / float(cols)))
    img = _on_checker(tex[:rows * ch, :cols * cw])
    d = ImageDraw.Draw(img)
    font = _font()
    for k in range(rows * cols):
        c, r = k % cols, k // cols
        x0, y0 = c * cw, r * ch
        d.rectangle([x0, y0, x0 + cw - 1, y0 + ch - 1], outline=(90, 90, 110))
        if k < n:
            yb = y0 + ch - foot_px
            d.line([x0 + 1, yb, x0 + cw - 2, yb], fill=(230, 40, 40))
            d.line([x0 + cw // 2, yb - 4, x0 + cw // 2, yb + 4], fill=(40, 90, 230))
    for name, first, count in anims:
        c, r = first % cols, first // cols
        d.text((c * cw + 3, r * ch + 2), "%s %d+%d" % (name, first, count), fill=(20, 20, 20), font=font)
    return img


def preview_fx(strips):
    width = max(cols * cw for _, _, cw, _, cols, _ in strips)
    width = max(width, max(cw * n for _, _, cw, _, _, n in strips))
    height = sum(ch + 14 for _, _, _, ch, _, _ in strips)
    img = Image.new("RGB", (width, height), (60, 60, 70))
    d = ImageDraw.Draw(img)
    font = _font()
    y = 0
    for eff, tex, cw, ch, cols, n in strips:
        d.text((3, y), eff, fill=(255, 255, 255), font=font)
        y += 14
        for k in range(n):
            c, r = k % cols, k // cols
            cell = tex[r * ch:(r + 1) * ch, c * cw:(c + 1) * cw]
            img.paste(_on_checker(cell), (k * cw, y))
            d.rectangle([k * cw, y, k * cw + cw - 1, y + ch - 1], outline=(90, 90, 110))
        y += ch
    return img


def preview_bg(layers):
    rows = []
    if "far" in layers:
        rows.append(np.concatenate([layers["far"]] * 2, axis=1))
    if "near" in layers:
        near = np.concatenate([layers["near"]] * 2, axis=1)
        if "far" in layers:
            base = rows[0][..., :3].astype(np.float32)
            a = near[..., 3:4].astype(np.float32) / 255.0
            rgb = near[..., :3] * a + base * (1 - a)
            rows.append(np.dstack([rgb, np.full(rgb.shape[:2], 255.0)]).astype(np.uint8))
        else:
            rows.append(near)
    img = Image.new("RGB", (2 * BG_W, len(rows) * (BG_H + 6)), (40, 40, 40))
    d = ImageDraw.Draw(img)
    for i, r in enumerate(rows):
        img.paste(_on_checker(r), (0, i * (BG_H + 6)))
        d.line([BG_W, i * (BG_H + 6) + BG_H, BG_W, i * (BG_H + 6) + BG_H + 5], fill=(255, 60, 60))
    return img


def preview_ui(tex, slice_):
    h, w = tex.shape[:2]
    shown = [_on_checker(tex)]
    if slice_ and 2 * slice_ < min(w, h):
        # the same art stretched with 9-slice to 1.6 x 1.3 of its size
        W2, H2 = int(w * 1.6), int(h * 1.3)
        out = np.zeros((H2, W2, 4), np.uint8)
        xs = [(0, slice_, 0, slice_), (slice_, w - slice_, slice_, W2 - slice_), (w - slice_, w, W2 - slice_, W2)]
        ys = [(0, slice_, 0, slice_), (slice_, h - slice_, slice_, H2 - slice_), (h - slice_, h, H2 - slice_, H2)]
        for sy0, sy1, dy0, dy1 in ys:
            for sx0, sx1, dx0, dx1 in xs:
                piece = Image.fromarray(np.ascontiguousarray(tex[sy0:sy1, sx0:sx1]), "RGBA")
                out[dy0:dy1, dx0:dx1] = np.asarray(piece.resize((dx1 - dx0, dy1 - dy0), BICUBIC))
        shown.append(_on_checker(out))
    W = sum(i.width for i in shown) + 10 * (len(shown) - 1)
    img = Image.new("RGB", (W, max(i.height for i in shown)), (40, 40, 40))
    x = 0
    for i in shown:
        img.paste(i, (x, 0))
        x += i.width + 10
    if slice_:
        d = ImageDraw.Draw(img)
        for v in (slice_, w - slice_):
            d.line([v, 0, v, h - 1], fill=(255, 60, 60))
        for v in (slice_, h - slice_):
            d.line([0, v, w - 1, v], fill=(255, 60, 60))
    return img


def preview_icons(tiles):
    w = sum(t.shape[1] + 8 for _, t in tiles)
    h = max(t.shape[0] for _, t in tiles) + 16
    img = Image.new("RGB", (w, h), (60, 60, 70))
    d = ImageDraw.Draw(img)
    font = _font()
    x = 0
    for name, t in tiles:
        img.paste(_on_checker(t), (x, 0))
        d.text((x + 2, t.shape[0] + 2), name, fill=(255, 255, 255), font=font)
        x += t.shape[1] + 8
    return img


