#!/usr/bin/env python3
"""Turn the artist's PNG images into game textures and the Lua art manifest.

The artist makes images with an image model from the prompts built from
tools/asset_spec.py and puts them in art_src/, named exactly like the sheet
files in the spec (hero_mage_horde_f_A.png, mob_wolf.png, bg_forest_far.png...).
This script

  * removes the background: real transparency, a flat magenta (#FF00FF) fill,
    or a near-uniform light/dark fill with JPEG-like noise; it softens the
    edges, removes magenta fringes and drops stray specks,
  * finds the frames on sprite and effect sheets (connected drawings, with
    detached bits such as weapon tips or sparks joined to the nearest frame),
    sorts them into the spec's rows and orders each row left to right,
  * scales each character once for all its frames, puts the feet on a common
    baseline, centres them, and packs the frames into power-of-two textures,
  * cuts battle backgrounds into seamless 1024x256 strips and fits interface
    frames and icons to their target sizes,
  * writes 32-bit uncompressed TGA files (bottom-left origin) to
    BigWowIdle/Media/Art/, the manifest BigWowIdle/Data/Art.lua,
    and one contact sheet per asset to tests/out/art/ to check by eye.

Usage
    python3 tools/import_art.py                  import everything present in art_src/
    python3 tools/import_art.py --check          list present / missing / unexpected images (writes nothing)
    python3 tools/import_art.py --only mob_wolf 'hero_mage_*'
                                                 re-process only these assets; the rest of the
                                                 manifest and textures stay as they were
Options
    --src DIR       the artist's images            (default: art_src/)
    --out DIR       the add-on folder to write to  (default: BigWowIdle/)
    --preview DIR   contact sheets                 (default: tests/out/art/)
    --no-preview    do not write contact sheets
    --debug         stop with a traceback when an asset fails

Needs Pillow and numpy only.
"""
