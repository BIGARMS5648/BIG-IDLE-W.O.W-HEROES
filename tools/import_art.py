class Result:
    def __init__(self):
        self.entries = []        # (section, key, entry)
        self.textures = {}       # name -> uint8 RGBA
        self.preview = None      # PIL image
        self.summary = ""


def _sheet_path(src, sh):
    p = os.path.join(src, sh["file"])
    return p if os.path.isfile(p) else None


def process_sprite(a, src, log):
    cell = a["cell"]
    if isinstance(cell, (tuple, list)):
        cw, ch = int(cell[0]), int(cell[1])   # wide cells leave room for weapons
    else:
        cw = ch = cell
    foot_px = int(round(FOOT * ch))
    cols = a.get("cols") or max(n for s in a["sheets"] for _, n in s["rows"])
    crops, anim_of, anims = [], [], []
    sheet_heights = []
    for si, sh in enumerate(a["sheets"]):
        path = _sheet_path(src, sh)
        if not path:
            names = ", ".join(n for n, _ in sh["rows"])
            if si == 0 and len(a["sheets"]) > 1:
                log.warn(sh["file"], "missing (%s come from it); importing the other sheet only" % names)
            else:
                log.note(sh["file"], "not supplied, so %s are not imported yet" % names)
            continue
        rgba, _ = prepare(path, sh["file"], log)
        found, lab, r = find_frames(rgba[..., 3], sh["rows"], sh["file"], log, "sprite")
        heights = {}
        for (anim, _), frs in zip(sh["rows"], found):
            if not frs:
                continue
            first = len(crops)
            for f in frs:
                c = extract(rgba, lab, f, r)
                if c is not None:
                    crops.append(c)
                    anim_of.append(anim)
            if len(crops) > first:
                anims.append((anim, first, len(crops) - first))
                heights[anim] = [metrics(c)["h"] for c in crops[first:]]
        sheet_heights.append((sh["file"], heights))
    if not crops:
        raise AssetError("no frames found")

    # one size for the whole character: the second sheet should match the first
    if len(sheet_heights) == 2:
        (fa, ha), (fb, hb) = sheet_heights
        if ha.get("idle") and hb.get("hit"):
            ratio = float(np.median(hb["hit"]) / np.median(ha["idle"]))
            if not 0.8 <= ratio <= 1.25:
                log.warn(fb, "the character looks %d%% %s than on %s (hit vs idle height); "
                         "both sheets share one scale" % (abs(round((ratio - 1) * 100)), "larger" if ratio > 1 else "smaller", fa))

    mets = [metrics(c) for c in crops]
    counts = {an: c for an, _, c in anims}
    normal = [i for i, an in enumerate(anim_of) if an in ("idle", "walk")] or \
             [i for i, an in enumerate(anim_of) if an != "death"] or list(range(len(crops)))
    hs = np.array([mets[i]["h"] for i in normal], np.float64)
    med = float(np.median(hs))
    usual = hs[(hs >= 0.75 * med) & (hs <= 1.3 * med)]
    tallest = float(usual.max()) if len(usual) else med
    s0 = FILL * ch / tallest
    med_w = float(np.median([m["w"] for m in mets]))
    spec_counts = {n: c for sh in a["sheets"] for n, c in sh["rows"]}
    suspect = [i for i, an in enumerate(anim_of)
               if mets[i]["w"] > 2.0 * med_w and counts.get(an, 0) < spec_counts.get(an, 0)]

    def fit(i):
        m = mets[i]
        up = m["bottom"] - m["stop"] + 1
        half = max(m["ax"] - m["sleft"], m["sright"] + 1 - m["ax"], 1.0)
        return min((ch - foot_px - EDGE) / up, (cw / 2.0 - EDGE) / half)

    # wide bodies (beasts) are sized by their idle/walk frames; any other frame that
    # still does not fit shrinks the whole character, which is worth a warning
    s_norm = min([s0] + [fit(i) for i in normal if i not in suspect])
    s = s_norm
    limiter = None
    for i in range(len(crops)):
        if i in suspect:
            continue
        f = fit(i)
        if f < s:
            s, limiter = f, i
    if limiter is not None and s < 0.9 * s_norm:
        an = anim_of[limiter]
        first = next(fi for n2, fi, _ in anims if n2 == an)
        log.warn(a["id"], "frame %s #%d is too wide or tall for the cell: the whole character is drawn %d%% smaller"
                 % (an, limiter - first + 1, round((1 - s / s_norm) * 100)))
    for i in suspect:
        an = anim_of[i]
        first = next(fi for n2, fi, _ in anims if n2 == an)
        log.warn(a["id"], "frame %s #%d looks like two frames drawn together; shrunk on its own to fit" % (an, i - first + 1))

    nframes = len(crops)
    nrows = int(math.ceil(nframes / float(cols)))
    if nrows * ch > MAX_TEX:
        keep = (MAX_TEX // ch) * cols
        log.warn(a["id"], "%d frames do not fit a %d texture; dropping the last %d" % (nframes, MAX_TEX, nframes - keep))
        nframes, nrows = keep, MAX_TEX // ch
    tw, th = pot(cols * cw), pot(nrows * ch)
    tex = np.zeros((th, tw, 4), np.float32)
    clipped = 0
    for k in range(nframes):
        c = crops[k]
        sk = min(s, fit(k)) if k in suspect else s
        img = resize_rgba(c, round(c.shape[1] * sk), round(c.shape[0] * sk))
        m = metrics(img)
        col, row = k % cols, k // cols
        x = col * cw + int(round(cw / 2.0 - m["ax"]))
        y = row * ch + (ch - foot_px - 1 - m["bottom"])
        if paste(tex, img, x, y, (col * cw, row * ch, (col + 1) * cw, (row + 1) * ch)) > 0.1:
            clipped += 1
    if clipped:
        log.warn(a["id"], "%d frame(s) slightly clipped at the cell border" % clipped)
    anims = [(n, f, min(c, nframes - f)) for n, f, c in anims if f < nframes]
    res = Result()
    res.textures[a["id"]] = to_u8(bleed(tex))
    entry = dict(file=a["id"], w=tw, h=th, cw=cw, ch=ch, cols=cols, foot=round(foot_px / float(ch), 4),
                 facing=a.get("facing", "right"), anims={n: [f, c] for n, f, c in anims})
    if a.get("game"):
        entry["game"] = a["game"]
    res.entries.append(("sprites", a["id"], entry))
    res.preview = preview_sprite(res.textures[a["id"]], cw, ch, cols, nframes, foot_px, anims)
    res.summary = "%d frames -> %dx%d, scale %.2f (%s)" % (
        nframes, tw, th, s, ", ".join("%s %d" % (n, c) for n, _, c in anims))
    return res


def grid_for(n, cw, ch):
    best = None
    for cols in range(1, n + 1):
        rows = int(math.ceil(n / float(cols)))
        w, h = pot(cols * cw), pot(rows * ch)
        if w > MAX_TEX or h > MAX_TEX:
            continue
        key = (w * h, abs(math.log(w / float(h), 2)), -cols)
        if best is None or key < best[0]:
            best = (key, cols, w, h)
    return best[1:]


def process_fx(a, src, log):
    sh = a["sheets"][0]
    path = _sheet_path(src, sh)
    fields = a["id"].startswith("fx_fields")
    cw = a["cell"]
    ch = cw // 2 if fields else cw
    pad = max(EDGE, int(round(FX_PAD * ch)))
    rgba, _ = prepare(path, sh["file"], log)
    found, lab, r = find_frames(rgba[..., 3], sh["rows"], sh["file"], log, "fx")
    res = Result()
    strips = []
    for (eff, _), frs in zip(sh["rows"], found):
        if not frs:
            continue
        crops = [c for c in (extract(rgba, lab, f, r) for f in frs) if c is not None]
        if not crops:
            continue
        avail_w = cw - 2 * pad
        avail_h = (ch - pad - EDGE) if fields else (ch - 2 * pad)
        s = min(min(avail_w / float(c.shape[1]), avail_h / float(c.shape[0])) for c in crops)
        s = min(s, FX_MAX_UPSCALE)
        cols, tw, th = grid_for(len(crops), cw, ch)
        tex = np.zeros((th, tw, 4), np.float32)
        for k, c in enumerate(crops):
            img = resize_rgba(c, round(c.shape[1] * s), round(c.shape[0] * s))
            sy, sx = np.nonzero(img[..., 3] > 0.02)
            if not len(sy):
                continue
            col, row = k % cols, k // cols
            x = col * cw + int(round(cw / 2.0 - (sx.min() + sx.max() + 1) / 2.0))
            if fields:
                y = row * ch + (ch - EDGE - int(sy.max()) - 1)
            else:
                y = row * ch + int(round(ch / 2.0 - (sy.min() + sy.max() + 1) / 2.0))
            paste(tex, img, x, y, (col * cw, row * ch, (col + 1) * cw, (row + 1) * ch))
        res.textures[eff] = to_u8(bleed(tex))
        res.entries.append(("fx", eff, dict(file=eff, w=tw, h=th, cw=cw, ch=ch, cols=cols, n=len(crops))))
        strips.append((eff, res.textures[eff], cw, ch, cols, len(crops)))
    if not res.entries:
        raise AssetError("no effect frames found")
    res.preview = preview_fx(strips)
    res.summary = "%s (cells %dx%d)" % (", ".join("%s %d" % (e["file"], e["n"]) for _, _, e in res.entries), cw, ch)
    return res


def _wrap(img, out_w, fade):
    """img is out_w + fade wide; blend its last `fade` columns over its first ones so
    column out_w - 1 continues straight into column 0 when the strip repeats."""
    a = img[..., 3:4]
    pm = np.concatenate([img[..., :3] * a, a], axis=2)
    t = (np.arange(fade, dtype=np.float32) + 0.5) / fade
    t = (t * t * (3 - 2 * t))[None, :, None]
    out = pm[:, :out_w].copy()
    out[:, :fade] = pm[:, out_w:out_w + fade] * (1 - t) + pm[:, :fade] * t
    al = out[..., 3]
    nz = al > 1e-6
    out[..., :3][nz] = np.minimum(out[..., :3][nz] / al[nz][:, None], 1.0)
    out[..., :3][~nz] = 0
    return out


def process_background(a, src, log):
    res = Result()
    parts = {}
    layers = []
    for sh in a["sheets"]:
        path = _sheet_path(src, sh)
        if not path:
            log.note(sh["file"], "not supplied")
            continue
        which = "far" if sh["file"].endswith("_far.png") else "near"
        name = sh["file"][:-4]
        if which == "far":
            img, _ = load_image(path)
            al = img[..., 3:4]
            if (al < 0.99).any():
                mean = (img[..., :3] * al).sum((0, 1)) / max(float(al.sum()), 1e-6)
                img[..., :3] = img[..., :3] * al + mean[None, None, :] * (1 - al)
            img[..., 3] = 1.0
        else:
            img, _ = prepare(path, sh["file"], log, holes=False, need_bg=False)
        H, W = img.shape[:2]
        wide = BG_W + BG_FADE
        s = max(wide / float(W), BG_H / float(H))
        img = resize_rgba(img, round(W * s), round(H * s))
        Hs, Ws = img.shape[:2]
        x0 = (Ws - wide) // 2
        if which == "far":
            y0 = int(round(BG_FAR_CENTRE * Hs - BG_H / 2.0))
            y0 = min(max(0, y0), Hs - BG_H)
            band = img[y0:y0 + BG_H, x0:x0 + wide]
        else:
            rows = np.nonzero(img[..., 3].mean(axis=1) > 0.02)[0]
            if not len(rows):
                log.warn(sh["file"], "nothing drawn (empty after background removal)")
                continue
            bottom = int(rows[-1]) + 1
            band = np.zeros((BG_H, wide, 4), np.float32)
            top = max(0, bottom - BG_H)
            piece = img[top:bottom, x0:x0 + wide]
            band[BG_H - piece.shape[0]:] = piece
            if top > 0 and (img[:top, x0:x0 + wide, 3] > 0.5).mean() > 0.01:
                log.note(sh["file"], "the drawing is taller than the kept bottom %d rows; its top is cut" % BG_H)
        out = _wrap(band, BG_W, BG_FADE)
        res.textures[name] = to_u8(bleed(out) if which == "near" else out)
        parts[which] = dict(file=name, w=BG_W, h=BG_H)
        layers.append((which, res.textures[name]))
    if not parts:
        raise AssetError("no background layers")
    res.entries.append(("bg", a["game"]["theme"], parts))
    res.preview = preview_bg(dict(layers))
    res.summary = ", ".join("%s %dx%d" % (k, BG_W, BG_H) for k in ("far", "near") if k in parts)
    return res


def process_ui(a, src, log):
    sh = a["sheets"][0]
    rgba, _ = prepare(_sheet_path(src, sh), sh["file"], log, need_bg=False)
    img = trim(rgba, 0.2)            # the faint outer fringe does not count as the frame's edge
    if img is None:
        raise AssetError("nothing drawn (empty after background removal)")
    w, h = a["size"]
    if pot(w) != w or pot(h) != h:
        log.warn(a["id"], "target size %dx%d is not a power of two; written as is" % (w, h))
    out = resize_rgba(img, w, h)
    res = Result()
    res.textures[a["id"]] = to_u8(bleed(out))
    entry = dict(file=a["id"], w=w, h=h)
    if a.get("slice") is not None:
        entry["slice"] = a["slice"]
    res.entries.append(("ui", a["id"], entry))
    res.preview = preview_ui(res.textures[a["id"]], a.get("slice"))
    res.summary = "%dx%d%s (from %dx%d)" % (w, h, ", slice %d" % a["slice"] if a.get("slice") else "", img.shape[1], img.shape[0])
    return res


def process_icons(a, src, log):
    sh = a["sheets"][0]
    ids = a["icons"]
    rows = []
    for i in range(0, len(ids), 4):
        rows.append(("row %d" % (i // 4 + 1), len(ids[i:i + 4])))
    rgba, _ = prepare(_sheet_path(src, sh), sh["file"], log)
    found, lab, r = find_frames(rgba[..., 3], rows, sh["file"], log, "icons")
    frames = [f for g in found if g for f in g]     # reading order; count problems were reported per row
    w, h = a["size"]
    res = Result()
    tiles = []
    for icon_id, f in zip(ids, frames):
        c = extract(rgba, lab, f, r)
        if c is None:
            continue
        s = min((w - 2 * ICON_PAD) / float(c.shape[1]), (h - 2 * ICON_PAD) / float(c.shape[0]))
        img = resize_rgba(c, round(c.shape[1] * s), round(c.shape[0] * s))
        tex = np.zeros((h, w, 4), np.float32)
        paste(tex, img, (w - img.shape[1]) // 2, (h - img.shape[0]) // 2, (0, 0, w, h))
        res.textures[icon_id] = to_u8(bleed(tex))
        res.entries.append(("icons", icon_id, dict(file=icon_id, w=w, h=h)))
        tiles.append((icon_id, res.textures[icon_id]))
    if not tiles:
        raise AssetError("no icons found")
    res.preview = preview_icons(tiles)
    res.summary = "%d icons %dx%d" % (len(tiles), w, h)
    return res


