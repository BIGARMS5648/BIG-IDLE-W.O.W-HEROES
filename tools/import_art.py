class Frame:
    def __init__(self, core, area, lab_id):
        self.core = core                 # x0, y0, x1, y1 (exclusive) of the main drawing
        self.box = list(core)            # including attached bits
        self.area = area
        self.labels = [lab_id]

    @property
    def cy(self):
        return (self.core[1] + self.core[3]) / 2.0

    @property
    def cx(self):
        return (self.core[0] + self.core[2]) / 2.0

    @property
    def ch(self):
        return self.core[3] - self.core[1]

    def attach(self, box, lab_id):
        self.labels.append(lab_id)
        self.box = _union(self.box, box)

    def absorb(self, other):
        self.labels += other.labels
        self.box = _union(self.box, other.box)
        self.core = tuple(_union(self.core, other.core))
        self.area += other.area


def _union(a, b):
    return [min(a[0], b[0]), min(a[1], b[1]), max(a[2], b[2]), max(a[3], b[3])]


def _gaps(box, boxes):
    dx = np.maximum(0, np.maximum(boxes[:, 0] - box[2], box[0] - boxes[:, 2]))
    dy = np.maximum(0, np.maximum(boxes[:, 1] - box[3], box[1] - boxes[:, 3]))
    return np.hypot(dx, dy)


KIND_FRACS = {  # (seed: surely a frame, keep: smallest drawing kept as its own frame), x reference area
    "sprite": (0.2, 0.04),
    "fx": (0.06, 0.012),
    "icons": (0.15, 0.03),
}


def find_frames(alpha, rows, where, log, kind):
    """Returns (frames per spec row (list or None), label image, dilation radius)."""
    H, W = alpha.shape
    R = len(rows)
    mask = alpha > 0.25
    r = max(2, int(round(min(H, W) * 0.004)))
    lab, n = label(dilate(mask, r))
    if n == 0:
        log.warn(where, "nothing drawn (empty after background removal)")
        return [None] * R, lab, r
    ys, xs = np.nonzero(mask)
    lv = lab[ys, xs]
    area = np.bincount(lv, minlength=n + 1)
    x0 = np.full(n + 1, W, np.int64)
    y0 = np.full(n + 1, H, np.int64)
    x1 = np.zeros(n + 1, np.int64)
    y1 = np.zeros(n + 1, np.int64)
    np.minimum.at(x0, lv, xs)
    np.minimum.at(y0, lv, ys)
    np.maximum.at(x1, lv, xs + 1)
    np.maximum.at(y1, lv, ys + 1)
    ids = [i for i in range(1, n + 1) if area[i] > 0]
    ids.sort(key=lambda i: (-area[i], y0[i], x0[i]))
    expected = sum(c for _, c in rows)
    top = [area[i] for i in ids[:max(1, expected)]]
    ref = float(np.median(top))
    seed_f, keep_f = KIND_FRACS[kind]
    box = {i: (int(x0[i]), int(y0[i]), int(x1[i]), int(y1[i])) for i in ids}
    frames = [Frame(box[i], int(area[i]), i) for i in ids if area[i] >= seed_f * ref]
    rest = [i for i in ids if area[i] < seed_f * ref]
    if len(frames) > 1:
        cores = np.array([f.core for f in frames], np.float64)
        nn = [np.delete(_gaps(f.core, cores), k).min() for k, f in enumerate(frames)]
        typical_gap = float(np.median(nn))
    else:
        typical_gap = float(max(H, W))
    med_h = float(np.median([f.ch for f in frames])) if frames else 0.0
    attach_lim = max(2 * r + 1, min(0.45 * typical_gap, 0.5 * med_h))
    for i in rest:
        if frames:
            g = _gaps(box[i], np.array([f.core for f in frames], np.float64))
            k = int(g.argmin())
            if g[k] <= attach_lim:
                frames[k].attach(box[i], i)
                continue
        if area[i] >= keep_f * ref:          # smaller, far from everything: a speck, dropped
            frames.append(Frame(box[i], int(area[i]), i))
    full = [f.core[2] - f.core[0] for f in frames if f.area >= 0.5 * ref]
    ref_w = float(np.median(full)) if full else 0.0
    groups = _group_rows(frames, rows, H, ref, where, log)
    out = []
    for (name, want), g in zip(rows, groups):
        if g is None:
            out.append(None)
            continue
        g = _merge_close(sorted(g, key=lambda f: f.cx), want, ref_w)
        if len(g) > MAX_PER_ROW:
            log.warn(where, "row '%s': %d drawings, keeping the first %d" % (name, len(g), MAX_PER_ROW))
            g = g[:MAX_PER_ROW]
        if len(g) != want:
            log.warn(where, "row '%s': found %d frame%s, expected %d" % (name, len(g), "" if len(g) == 1 else "s", want))
        out.append(g)
    return out, lab, r


def _merge_close(g, want, ref_w):
    """A row with more drawings than the spec: join neighbours that are much closer to each
    other than the row's usual spacing (parts of one drawing, e.g. a trail of sparks), as
    long as the result is not as wide as two frames. Evenly spaced extra frames are kept."""
    while len(g) > want and len(g) >= 3:
        gaps = [float(_gaps(g[i].box, np.array([g[i + 1].box], np.float64))[0]) for i in range(len(g) - 1)]
        order = sorted(range(len(gaps)), key=lambda i: gaps[i])
        merged = False
        for i in order:
            others = gaps[:i] + gaps[i + 1:]
            if gaps[i] >= 0.5 * float(np.median(others)):
                break
            box = _union(g[i].box, g[i + 1].box)
            if ref_w and box[2] - box[0] > 1.75 * ref_w:
                continue
            g[i].absorb(g.pop(i + 1))
            merged = True
            break
        if not merged:
            break
    return g


def _group_rows(frames, rows, H, ref, where, log):
    R = len(rows)
    if not frames:
        log.warn(where, "no frames found")
        return [None] * R
    fs = sorted(frames, key=lambda f: f.cy)
    thr = max(3.0, 0.35 * float(np.median([f.ch for f in fs])))
    groups = [[fs[0]]]
    for f in fs[1:]:
        if f.cy - groups[-1][-1].cy > thr:
            groups.append([f])
        else:
            groups[-1].append(f)
    if len(groups) > R:
        big = [g for g in groups if max(f.area for f in g) >= 0.15 * ref]
        if len(big) >= R and len(big) < len(groups):
            log.warn(where, "ignored %d row(s) of small stray marks" % (len(groups) - len(big)))
            groups = big
        while len(groups) > R:      # a row split by uneven heights: join the closest neighbours
            gaps = [min(f.cy for f in groups[i + 1]) - max(f.cy for f in groups[i]) for i in range(len(groups) - 1)]
            i = int(np.argmin(gaps))
            groups[i] = groups[i] + groups.pop(i + 1)
    result = [None] * R
    if len(groups) == R:
        for i, g in enumerate(groups):
            result[i] = g
        return result
    # fewer rows than the spec: pick which spec rows they are (order kept), by frame count and height
    best = None
    for combo in itertools.combinations(range(R), len(groups)):
        cost = 0.0
        for g, ri in zip(groups, combo):
            cy = float(np.mean([f.cy for f in g]))
            cost += abs(len(g) - rows[ri][1]) + 4.0 * abs(cy / H - (ri + 0.5) / R)
        if best is None or cost < best[0] - 1e-9:
            best = (cost, combo)
    for g, ri in zip(groups, best[1]):
        result[ri] = g
    missing = ["'%s'" % rows[i][0] for i in range(R) if i not in best[1]]
    log.warn(where, "missing row%s %s (found %d of %d rows)" % ("s" if len(missing) > 1 else "", ", ".join(missing), len(groups), R))
    return result


def extract(rgba, lab, fr, r):
    H, W = lab.shape
    x0, y0 = max(0, fr.box[0] - r - 1), max(0, fr.box[1] - r - 1)
    x1, y1 = min(W, fr.box[2] + r + 1), min(H, fr.box[3] + r + 1)
    sub = rgba[y0:y1, x0:x1].copy()
    sub[..., 3] *= np.isin(lab[y0:y1, x0:x1], fr.labels)
    return trim(sub)


def metrics(img):
    a = img[..., 3]
    m = a > 0.5
    if m.sum() < 4:
        m = a > 0.1
    if not m.any():
        m = a > 0
    ys, xs = np.nonzero(m)
    top, bottom = int(ys.min()), int(ys.max())
    h = bottom - top + 1
    sel = ys >= bottom - (h - 1) * 0.25
    sy, sx = np.nonzero(a > 0.02)
    if not len(sy):
        sy, sx = ys, xs
    return dict(top=top, bottom=bottom, h=h, w=int(xs.max() - xs.min() + 1),
                ax=float(xs[sel].mean()) + 0.5, stop=int(sy.min()), sleft=int(sx.min()), sright=int(sx.max()))


